/*
 * Regenerates src/data/raw.ts from kanji-data.js.
 *
 * The corpus is ported mechanically rather than retyped so the factual fields
 * stay faithful to the source. Run after editing kanji-data.js:
 *
 *   node scripts/port-raw-data.mjs
 */

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { RADICALS, KANJI, VOCAB, SEED, LAPSES, ATTRIBUTION } from '../kanji-data.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const j = (x) => JSON.stringify(x)

const radicals = RADICALS.map(
  (r) => `  { c: ${j(r.c)}, m: ${j(r.m)}, level: ${r.level}, mn: ${j(r.mn)} },`,
).join('\n')

const kanji = KANJI.map(
  (k) =>
    `  { c: ${j(k.c)}, meanings: ${j(k.meanings)}, on: ${j(k.on)}, kun: ${j(k.kun)}, ` +
    `strokes: ${k.strokes}, grade: ${j(k.grade ?? null)}, jlpt: ${j(k.jlpt ?? null)}, ` +
    `level: ${k.level}, parts: ${j(k.parts || [])}, mn: ${j(k.mn)} },`,
).join('\n')

const vocab = VOCAB.map(
  (v) =>
    `  { c: ${j(v.c)}, meanings: ${j(v.meanings)}, reading: ${j(v.reading)}, ` +
    `level: ${v.level}, uses: ${j(v.uses || [])}, mn: ${j(v.mn)} },`,
).join('\n')

const seed = SEED.map((s) => `  ${j(s)},`).join('\n')
const lapses = Object.entries(LAPSES)
  .map(([k, v]) => `  ${j(k)}: ${v},`)
  .join('\n')

const file = `// Generated by scripts/port-raw-data.mjs from kanji-data.js - do not edit by hand.
//
// Factual fields (meanings, on/kun, strokes, grade, jlpt) follow the KANJIDIC2 /
// JMdict schema served by kanjiapi.dev (EDRDG, CC BY-SA). \`level\`, \`parts\` and
// \`mn\` are original to Kaidoku.

import type { ItemType } from '../types.ts'

export interface RawRadical {
  c: string
  m: string
  level: number
  mn: string
}

export interface RawKanji {
  c: string
  meanings: string[]
  on: string[]
  kun: string[]
  strokes: number
  grade: number | null
  jlpt: number | null
  level: number
  parts: string[]
  mn: string
}

export interface RawVocab {
  c: string
  meanings: string[]
  reading: string
  level: number
  uses: string[]
  mn: string
}

// [type, level, stage cycle, hours-until-due cycle (0 skips, negative is overdue)]
export type RawSeed = readonly [ItemType, number, readonly number[], readonly number[]]

export const RADICALS: readonly RawRadical[] = [
${radicals}
]

export const KANJI: readonly RawKanji[] = [
${kanji}
]

export const VOCAB: readonly RawVocab[] = [
${vocab}
]

export const SEED: readonly RawSeed[] = [
${seed}
]

export const LAPSES: Readonly<Record<string, number>> = {
${lapses}
}

export const ATTRIBUTION =
  ${j(ATTRIBUTION)}
`

writeFileSync(resolve(root, 'src/data/raw.ts'), file)
console.log(
  `src/data/raw.ts: ${RADICALS.length} radicals, ${KANJI.length} kanji, ${VOCAB.length} vocab`,
)
